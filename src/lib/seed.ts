const req = (
  id: string,
  data: Omit<ServiceRequest, 'id' | 'folio' | 'createdAt' | 'updatedAt' | 'history'> & {
    createdHoursAgo: number;
    historyStatuses: ServiceRequest['status'][];
  },
): ServiceRequest => {
  const createdAt = hoursAgo(data.createdHoursAgo);
  const history = data.historyStatuses.map((status, i) => ({
    status,
    at: new Date(new Date(createdAt).getTime() + i * 25 * 60 * 1000).toISOString(),
  }));
  return {
    ...data,
    id,
    folio: `RJ-2026-${id.slice(-4).toUpperCase()}`,
    createdAt,
    updatedAt: history[history.length - 1]?.at ?? createdAt,
    history,
  };
};

